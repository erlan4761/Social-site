/**
 * Сворачивает `ё` в `е`. Токенизатор `unicode61` кириллическое `ё` не трогает
 * ни при каком `remove_diacritics`, поэтому обе стороны сравнения нормализуются
 * вручную и одинаково: индекс — триггером в db.js, запрос — здесь. Иначе
 * «пленка» не находила бы «плёнку», а «ёлка» — «елку».
 */
export const foldSearchText = (s) => String(s).replace(/ё/g, 'е').replace(/Ё/g, 'Е');

// Сколько термов из запроса вообще учитывается. Потолок не про удобство, а про
// стоимость: каждый терм — отдельный обход индекса, и строка из сотни слов
// превратилась бы в способ занять процесс надолго.
const MAX_TERMS = 8;

/**
 * Строит безопасное выражение для `MATCH` или возвращает null, если искать
 * нечего.
 *
 * Сырой текст в `MATCH` подставлять нельзя: у FTS5 свой синтаксис, и обычная
 * человеческая строка легко оказывается в нём ошибкой — `a-b` даёт «no such
 * column: b», одинарная кавычка — незакрытую строку, `привет OR` — syntax
 * error, `*` — unknown special query. Поэтому запрос не экранируется, а
 * собирается заново: из текста берутся только буквы, цифры и `_`, всё
 * остальное считается разделителем.
 *
 * Каждый терм становится префиксным. Русского стеммера в SQLite нет, и взять
 * его неоткуда без новой зависимости, поэтому морфология решается началом
 * слова: `"проявк"*` находит «проявка», «проявки» и «проявкой». Цена честная —
 * поиск ищет по началу слова, а не по словоформе.
 *
 * Термы соединяются через AND: человек, набравший два слова, ждёт записи,
 * где есть оба, а не любое из них.
 *
 * @param {unknown} raw текст запроса как он пришёл от клиента
 * @returns {string | null}
 */
export function ftsQuery(raw) {
  // Не строка — искать нечего. Без этой ветки `undefined` превратился бы в
  // терм «undefined» и запрос молча искал бы слово, которого никто не набирал.
  if (typeof raw !== 'string') return null;

  const terms = foldSearchText(raw).toLowerCase()
    .split(/[^\p{L}\p{N}_]+/u)
    .filter((t) => t.length > 0)
    .slice(0, MAX_TERMS);

  if (!terms.length) return null;

  // Кавычки вокруг терма выключают разбор его содержимого как синтаксиса FTS5,
  // а удвоение внутренней кавычки — обычное экранирование строки. После
  // разбиения выше кавычек в терме остаться не может, но проверка стоит здесь,
  // а не в вызывающем коде: цена — одна операция, отказ от неё — инъекция.
  return terms.map((t) => `"${t.replace(/"/g, '""')}"*`).join(' AND ');
}
